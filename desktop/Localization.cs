using System.Globalization;

namespace CreateLauncher;

internal static class Localization
{
    public static string Language { get; private set; } = "ru";
    public static void SetLanguage(string? language) => Language = language == "en" ? "en" : "ru";
    public static string Text(string russian) => Language == "en" ? English.GetValueOrDefault(russian, russian) : russian;
    public static string Format(string russian, params object?[] args) => string.Format(
        CultureInfo.GetCultureInfo(Language), Text(russian), args);
    // Re-render existing status messages without repeating an operation or losing form input.
    public static string Translate(string text)
    {
        foreach (var (russian, english) in English)
        {
            var source = Language == "en" ? russian : english;
            var target = Language == "en" ? english : russian;
            if (text == source) return target;
        }
        foreach (var (russian, english) in English.OrderByDescending(p => p.Key.Length))
        {
            var source = Language == "en" ? russian : english;
            var target = Language == "en" ? english : russian;
            if (source.Contains("{0}"))
            {
                var parts = source.Split("{0}");
                if (text.StartsWith(parts[0], StringComparison.Ordinal) && text.EndsWith(parts[1], StringComparison.Ordinal)
                    && text.Length >= parts[0].Length + parts[1].Length)
                    return target.Replace("{0}", text.Substring(parts[0].Length, text.Length - parts[0].Length - parts[1].Length));
            }
            if (source.EndsWith(' ') && text.StartsWith(source, StringComparison.Ordinal))
                return target + text[source.Length..];
            if (source.StartsWith(' ') && text.EndsWith(source, StringComparison.Ordinal))
                return text[..^source.Length] + target;
        }
        return text;
    }
